-- 001_baseline: the Stacked Chat schema as it already exists in production
-- (read from the live project on 2026-10-15). Idempotent. It exists so a fresh
-- environment (CI, a Supabase branch, a new developer) can be built from scratch.
-- NOT needed on production: everything here is already there.

create table if not exists public.venues (
  id               uuid primary key default gen_random_uuid(),
  name             text not null,
  slug             text not null unique,
  tech_stack       jsonb,
  created_at       timestamptz default now(),
  logo_url         text,
  primary_color    text,
  bot_name         text,
  welcome_message  text,
  welcome_heading  text,
  white_label      boolean default false,
  workspace_id     text,
  dashboard_token  text
);

create table if not exists public.venue_members (
  id         uuid primary key default gen_random_uuid(),
  venue_id   uuid references public.venues(id),
  email      text not null,
  name       text not null,
  phone      text default '',
  role       text default 'staff',
  created_at timestamptz default now()
);

create table if not exists public.documents (
  id           bigint generated by default as identity primary key,
  filename     text,
  content      text,
  chunk_index  integer,
  created_at   timestamp default now(),
  workspace_id text,
  file_url     text
);

create table if not exists public.videos (
  id          bigint generated by default as identity primary key,
  url         text not null,
  title       text,
  description text,
  type        text default 'youtube',
  thumbnail   text,
  yt_id       text,
  tenant      text default 'stacked',
  created_at  timestamptz default now(),
  category    text default 'General'
);

create table if not exists public.conversations (
  id         bigint generated by default as identity primary key,
  email      text,
  name       text,
  venue      text,
  messages   jsonb,
  created_at timestamp default now(),
  updated_at timestamp default now(),
  venue_id   uuid references public.venues(id)
);

create table if not exists public.tickets (
  id           bigint generated by default as identity primary key,
  email        text,
  name         text,
  venue        text,
  issue        text,
  conversation jsonb,
  status       text default 'open',
  created_at   timestamp default now(),
  venue_id     uuid references public.venues(id),
  escalated    boolean default false
);

create table if not exists public.leads (
  id         bigint generated by default as identity primary key,
  name       text,
  venue      text,
  email      text,
  created_at timestamp default now(),
  venue_id   uuid references public.venues(id)
);

create table if not exists public.nps_scores (
  id         uuid primary key default gen_random_uuid(),
  vendor     text not null,
  score      integer not null,
  comment    text,
  venue_id   uuid references public.venues(id),
  venue      text,
  respondent text,
  created_at timestamptz default now()
);

create table if not exists public.images (
  id          uuid primary key default gen_random_uuid(),
  url         text,
  title       text,
  description text,
  tenant      text,
  created_at  timestamptz default now()
);
